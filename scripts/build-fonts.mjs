#!/usr/bin/env node
// Trims the Fontsource rules for the Japanese font to what the site uses. Rerun after updating Fontsource.
//   jp-font.css      Japanese and Latin slices at two weights, WOFF2 only
//   banner-font.css  just the slices that draw the Kanjimono banner's three kanji
import { readFile, writeFile } from 'node:fs/promises';

const faces = async (weight) => {
  const css = await readFile(`node_modules/@fontsource/m-plus-rounded-1c/${weight}.css`, 'utf8');
  return css.match(/@font-face \{[^}]+\}/g).map((rule) => ({
    css: rule
      .replace(/, url\([^)]+\.woff\) format\('woff'\)/, '')
      .replace('./files/', '@fontsource/m-plus-rounded-1c/files/'),
    script: /rounded-1c-([a-z-]+)-\d+-normal/.exec(rule)?.[1] ?? 'japanese',
    has: (c) => /unicode-range: ([^;]+)/.exec(rule)[1].split(',').some((r) => {
      const [from, to = from] = r.trim().replace('U+', '').split('-').map((h) => parseInt(h, 16));
      return c >= from && c <= to;
    }),
  }));
};
const head = '/* Generated by scripts/build-fonts.mjs. */\n';
const main = [];
for (const w of [500, 700]) main.push(...(await faces(w)).filter((f) => ['japanese', 'latin', 'latin-ext'].includes(f.script)));
await writeFile('src/styles/jp-font.css', head + main.map((f) => f.css).join('\n') + '\n');

const banner = [];
for (const w of [700, 900]) banner.push(...(await faces(w)).filter((f) => [...'火水木'].some((c) => f.has(c.codePointAt(0)))));
await writeFile('src/styles/banner-font.css', head + banner.map((f) => f.css).join('\n') + '\n');
