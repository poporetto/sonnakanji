#!/usr/bin/env node
// Drafts a scene for every kanji without a hand-made one, using the same rules:
// the tinted kanji with one object on each recognised part, or the strokes as
// the object when no part has a drawing. Writes scripts/art/scenes-auto.mjs.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { scenes } from './scenes.mjs';

const ROOT = path.resolve(import.meta.dirname, '../..');
const records = JSON.parse(readFileSync(path.join(ROOT, 'src/data/kanji.json'), 'utf8'));

const PART = {
  '亻': 'person:stand:green', '人': 'person:stand:green', '木': 'tree', '林': 'tree', '日': 'sun', '月': 'moon', '口': 'mouth', '女': 'person:stand:pink:long',
  '子': 'person:stand:yellow:bald', '氵': 'drop', '水': 'drop', '氺': 'drop', '冫': 'snow', '火': 'flame', '灬': 'flame', '田': 'field', '力': 'arm', '目': 'eye', '見': 'eye', '耳': 'ear',
  '門': 'gate', '言': 'bubble', '心': 'heart', '忄': 'heart', '手': 'hand', '扌': 'hand', '又': 'hand', '寸': 'hand', '攵': 'hand', '殳': 'hand', '宀': 'roof', '冖': 'roof', '广': 'roof:yellow', '尸': 'house',
  '土': 'mountain:brown', '山': 'mountain', '石': 'silver', '雨': 'cloud:blue', '金': 'nugget', '貝': 'shell', '車': 'cart', '馬': 'horse', '鳥': 'bird', '隹': 'bird:yellow', '羽': 'bird:white',
  '魚': 'fish', '牛': 'cow', '羊': 'sheep', '豕': 'pig', '⺨': 'dog', '犬': 'dog', '虫': 'bug', '糸': 'scarf', '竹': 'grass', '艹': 'grass', '禾': 'wheat', '米': 'wheat',
  '辶': 'road', '⻌': 'road', '彳': 'road', '行': 'crossroad', '走': 'person:run:orange', '足': 'foot', '止': 'foot', '食': 'bowl', '飠': 'bowl', '皿': 'bowl', '刀': 'knife', '刂': 'knife', '斤': 'axe',
  '矢': 'arrow', '弓': 'bow', '寺': 'temple', '里': 'house', '⻖': 'mountain:green', '⻏': 'house', '頁': 'head', '立': 'person:stand:teal', '穴': 'box', '欠': 'mouth', '礻': 'torii', '示': 'torii',
  '夕': 'moon', '白': 'sparkle', '青': 'flower:blue', '王': 'gem', '玉': 'gem', '衣': 'shirt', '衤': 'shirt', '巾': 'flag:red', '酉': 'cup', '戸': 'gate', '鬼': 'ghost', '彡': 'wind', '者': 'person:stand:orange:elder',
  '舟': 'cart', '古': 'cane', '生': 'sprout', '老': 'cane', '耂': 'cane', '文': 'paper', '書': 'paper', '音': 'note', '風': 'wind', '光': 'sparkle', '長': 'cane', '東': 'sun',
};
const PLAIN = ['brown', 'orange', 'green', 'blue', 'purple', 'red', 'teal'];

const lines = [];
for (const [i, r] of records.entries()) {
  if (scenes[r.kanji]) continue;
  const named = r.vg.parts.map((p, n) => [PART[p.el] ?? PART[p.original], n]).filter(([sprite]) => sprite).slice(0, 3);
  const layers = named.length
    ? ['kanji', ...named.map(([sprite, n]) => `${sprite} @${n} ${sprite === 'bubble' ? 0.55 : 0.6}`)]
    : [`strokes:${PLAIN[i % PLAIN.length]}:${Math.min(Math.max(17 - r.strokes, 6), 14)}`];
  lines.push(`${r.kanji}:[${['p', ...layers].map((l) => `'${l}'`).join(',')}],`);
}
writeFileSync(path.join(ROOT, 'scripts/art/scenes-auto.mjs'), `// Generated by auto-scenes.mjs. Move a line to scenes.mjs to hand-tune it.\nexport const scenes = {\n${lines.join('\n')}\n};\n`);
console.log(`${lines.length} drafted, ${lines.filter((l) => l.includes(' @')).length} with objects`);
